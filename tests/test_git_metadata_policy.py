import json
import re
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from scripts import _common, install, integration, isolation, pipeline_git


PURPOSE_BRANCH = re.compile(r'^(feature|feat|bugfix|fix|hotfix|release|chore)/[a-z0-9]+(?:[-.][a-z0-9]+)*$')


class GitMetadataPolicyTests(unittest.TestCase):
    def test_generated_branches_follow_conventional_branch_without_tool_prefixes(self):
        values = [pipeline_git.bound_branch_name(1), isolation.task_branch_name('T001'),
                  isolation.verify_branch_name('Wave-1.Cycle_2')]
        for branch in values:
            with self.subTest(branch=branch):
                self.assertRegex(branch, PURPOSE_BRANCH)
                self.assertNotRegex(branch, r'(?i)gsd|claude|codex|copilot|cursor|opencode')
        self.assertEqual(values[0], 'feature/milestone-001')
        self.assertEqual(values[1], 'chore/task-t001')
        self.assertTrue(pipeline_git.is_bound_branch(values[0]))
        self.assertEqual(pipeline_git.milestone_number(values[0]), 1)

    def test_member_inspect_branch_follows_the_metadata_rule(self):
        branch = isolation.member_inspect_branch_name('Acme App', 'web')
        self.assertEqual(branch, 'chore/verify-acme-app-inspect-web')
        self.assertRegex(branch, PURPOSE_BRANCH)
        self.assertNotRegex(branch, r'(?i)gsd|claude|codex|copilot|cursor|opencode')
        self.assertNotEqual(branch, isolation.verify_branch_name('acme-app-web'))

    def test_member_rebase_branch_and_commit_follow_the_metadata_rule(self):
        branch = isolation.member_rebase_branch_name('feature/acme-milestone-001', 'web')
        self.assertEqual(branch, 'chore/rebase-acme-milestone-001-web')
        self.assertRegex(branch, PURPOSE_BRANCH)
        self.assertNotRegex(branch, r'(?i)gsd|claude|codex|copilot|cursor|opencode')
        message = isolation._member_rebase_message({
            'member': 'web', 'branch': 'feature/acme-milestone-001', 'onto': 'a' * 40,
            'old_base': 'b' * 40, 'old_tip': 'c' * 40, 'new_tip': 'd' * 40, 'receipt_digest': 'e' * 64})
        self.assertTrue(message.startswith('chore: adopt rebased member web onto aaaaaaaaaaaa\n\n'))
        self.assertIsNone(_common.TOOL_ATTRIBUTION_RE.search(message))
        self.assertNotRegex(message, r'(?i)gsd|generated|co-authored-by|claude')

    def test_pr_body_and_subject_have_no_tool_credit(self):
        branch = pipeline_git.bound_branch_name(1)
        body = integration.pull_request_body('.project/archive/001-example', 'a' * 40, branch)
        title = pipeline_git.integrate_subject('001-example', 'main')
        self.assertNotRegex(body + title, r'(?i)gsd|generated.by|prepared.with|co-authored-by|claude')
        self.assertIn('Archive:', body)
        self.assertIn('Ship:', body)

    def test_legacy_attribution_is_removed_without_losing_human_content(self):
        lines = ['PR prepared with GSD Path.', 'Generated by Claude Code',
                 'Generated with OpenAI Codex', 'Co-Authored-By: Claude <noreply@anthropic.com>',
                 'Generated by ChatGPT', 'Session: https://claude.ai/code/session-example']
        for attribution in lines:
            with self.subTest(attribution=attribution):
                self.assertIsNotNone(_common.TOOL_ATTRIBUTION_RE.search(attribution))
                self.assertEqual(_common.without_tool_attribution('Human explanation\n\n---\n' + attribution),
                                 'Human explanation')
        self.assertEqual(_common.without_tool_attribution('Files: .claude/settings.json\nReviewed by a person'),
                         'Files: .claude/settings.json\nReviewed by a person')
        self.assertEqual(_common.without_tool_attribution('Human explanation\n\n---\n'),
                         'Human explanation\n\n---\n')

    def test_host_commit_and_pr_attribution_are_disabled(self):
        settings = json.loads(install.claude_hooks_settings('python3'))
        self.assertEqual(settings['attribution'], {'commit': '', 'pr': '', 'sessionUrl': False})

    def test_attribution_is_disabled_without_enabling_optional_hooks(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            destination = root / '.claude/settings.json'
            destinations = install._project_destinations(root, ['claude'], False, 'python3', None)
            content = next(literal for path, _, literal, _ in destinations if path == destination)
            settings = json.loads(content)
            self.assertNotIn('hooks', settings)
            self.assertEqual(settings['attribution'], {'commit': '', 'pr': '', 'sessionUrl': False})
            destination.parent.mkdir()
            destination.write_text(json.dumps({'env': {'EXAMPLE_SETTING': 'kept'},
                                              'attribution': {'commit': 'old attribution'}}))
            merged = json.loads(install._merged_claude_attribution_settings(destination, 'python3'))
            self.assertEqual(merged['env'], {'EXAMPLE_SETTING': 'kept'})
            self.assertEqual(merged['attribution'], settings['attribution'])
            sidecar = json.loads(isolation._member_hook_configs(root)['.claude/settings.json'])
            self.assertNotIn('hooks', sidecar)
            self.assertEqual(sidecar['attribution'], settings['attribution'])

    def test_commit_message_hook_rejects_generated_tool_trailers(self):
        script = Path(__file__).resolve().parents[1] / 'scripts/git_guard.py'
        with tempfile.TemporaryDirectory() as directory:
            repo = Path(directory)
            def git(*args):
                return subprocess.run(['git', '-c', 'user.name=Test', '-c',
                                       'user.email=test@example.invalid', *args], cwd=repo,
                                      text=True, capture_output=True, check=True)
            git('init', '-q', '-b', 'main')
            (repo / 'app.py').write_text('value = 1\n')
            git('add', 'app.py')
            git('commit', '-qm', 'initial')
            (repo / 'app.py').write_text('value = 2\n')
            git('add', 'app.py')
            message = repo / 'message.txt'
            message.write_text('fix: update value\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n')
            result = subprocess.run([sys.executable, '-B', str(script), 'commit-msg', str(message)],
                                    cwd=repo, text=True, capture_output=True)
            self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
            self.assertIn('must not contain tool attribution', result.stderr)
            message.write_text('fix: update value\n')
            result = subprocess.run([sys.executable, '-B', str(script), 'commit-msg', str(message)],
                                    cwd=repo, text=True, capture_output=True)
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)


if __name__ == '__main__':
    unittest.main()
